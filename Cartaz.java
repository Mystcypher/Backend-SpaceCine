public class Cartaz {

    public String titulo;
    public String imagem;
    public int class_indic;
    public int dt_est;
    public String genero;
    public int duracao;

    public Cartaz(String titulo, String imagem, int class_indic, int dt_est, String genero, int duracao) {
        this.titulo = titulo;
        this.imagem = imagem;
        this.class_indic = class_indic;
        this.dt_est = dt_est;
        this.genero = genero;
        this.duracao = duracao;
    }
}